void OLED_DrawCar(uint8_t x, uint8_t y,uint8_t direction)
{
	OLED_DrawPixel(x,y);
	
	OLED_DrawPixel(x-1,y);//middle
	OLED_DrawPixel(x-2,y);
	OLED_DrawPixel(x-3,y);
	OLED_DrawPixel(x-4,y);
	OLED_DrawPixel(x+1,y);
	OLED_DrawPixel(x+2,y);
	OLED_DrawPixel(x+3,y);
	OLED_DrawPixel(x+4,y);
	
	OLED_DrawPixel(x,y-1);
	OLED_DrawPixel(x,y-2);
	OLED_DrawPixel(x,y-3);
	OLED_DrawPixel(x,y-4);
	OLED_DrawPixel(x,y+1);
	OLED_DrawPixel(x,y+2);
	OLED_DrawPixel(x,y+3);
	OLED_DrawPixel(x,y+4);

	switch(direction)
	{
		case('W'):
		{
			OLED_DrawPixel(x,y-7);
			OLED_DrawPixel(x,y-8);
			OLED_DrawPixel(x-1,y-7);
			OLED_DrawPixel(x+1,y-7);
			break;
		}
		case('A'):
		{
			OLED_DrawPixel(x-7,y+1);
			OLED_DrawPixel(x-7,y-1);
			OLED_DrawPixel(x-7,y);
			OLED_DrawPixel(x-8,y);
			break;
		}
		case('S'):
		{
			OLED_DrawPixel(x,y+7);
			OLED_DrawPixel(x,y+8);
			OLED_DrawPixel(x-1,y+7);
			OLED_DrawPixel(x+1,y+7);
			break;
		}
		case('D'):
		{
			OLED_DrawPixel(x+7,y+1);
			OLED_DrawPixel(x+7,y-1);
			OLED_DrawPixel(x+7,y);
			OLED_DrawPixel(x+8,y);
			break;
		}
	}
}

void OLED_DrawLine(uint8_t pos1[2], uint8_t pos2[2])//ai写的
{
    int x0 = pos1[0];
    int y0 = pos1[1];
    int x1 = pos2[0];
    int y1 = pos2[1];

    int dx = x1 - x0;
    int dy = y1 - y0;

    // x 方向环形处理：选择较短的路径
    if (dx > 128 / 2) {
        dx -= 128;
    } else if (dx < -(128 / 2)) {
        dx += 128;
    }

    // y 方向环形处理：选择较短的路径
    if (dy > 64 / 2) {
        dy -= 64;
    } else if (dy < -(64 / 2)) {
        dy += 64;
    }

    // 步数取 |dx| 和 |dy| 的较大值，保证每个方向步进不超过 1 像素
    int steps = (abs(dx) > abs(dy)) ? abs(dx) : abs(dy);
    if (steps == 0) {
        OLED_DrawPixel((uint8_t)x0, (uint8_t)y0);
        return;
    }

    for (int i = 0; i <= steps; i++) {
        // 线性插值
        int x = x0 + (dx * i) / steps;
        int y = y0 + (dy * i) / steps;

        // x 环形映射回 0~127
        x %= 128;
        if (x < 0) x += 128;

        // y 环形映射回 0~63
        y %= 64;
        if (y < 0) y += 64;

        OLED_DrawPixel((uint8_t)x, (uint8_t)y);
    }
}

